import {readdir, readFile, writeFile} from "node:fs/promises";
import {extname, relative, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const knowledgeRoot = resolve(root, "FACETEST/knowledge");
const output = resolve(root, "api/_facetest-knowledge.generated.mjs");

async function walk(directory) {
  const entries = await readdir(directory, {withFileTypes: true});
  const files = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if ([".md", ".markdown", ".txt"].includes(extname(entry.name).toLowerCase())) files.push(path);
  }
  return files;
}

function stripFrontmatter(value) {
  return value.replace(/^---\s*\n[\s\S]*?\n---\s*\n?/, "").trim();
}

function titleOf(value, path) {
  return value.match(/^#\s+(.+)$/m)?.[1]?.trim() || path.split("/").at(-1)?.replace(/\.[^.]+$/, "") || "Adam Cagle";
}

function chunks(value) {
  return stripFrontmatter(value)
    .split(/\n(?=#{1,3}\s)|\n{2,}/)
    .map((part) => part.replace(/^#{1,3}\s+/, "").replace(/\s+/g, " ").trim())
    .filter((part) => part.length >= 28)
    .flatMap((part) => part.length <= 1100 ? [part] : part.match(/[\s\S]{1,1000}(?:\s|$)/g) || [part]);
}

const records = [];
for (const path of await walk(knowledgeRoot)) {
  const raw = await readFile(path, "utf8");
  const source = relative(root, path);
  const title = titleOf(raw, source);
  chunks(raw).forEach((text, index) => records.push({id: `${source}#${index + 1}`, title, source, text}));
}

const banner = "// Generated by scripts/build-facetest-knowledge.mjs. Do not edit by hand.\n";
await writeFile(output, `${banner}export const ADAM_KNOWLEDGE = ${JSON.stringify(records, null, 2)};\n`);
console.log(`Compiled ${records.length} Adam knowledge chunks into ${relative(root, output)}`);
